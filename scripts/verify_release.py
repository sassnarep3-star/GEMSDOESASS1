#!/usr/bin/env python3
"""Offline, stdlib-only checks for the frozen negative release and static site.

Does not infer scientific approval or need raw raster caches. Test fixtures are
kept in temporary directories; no competition TIFF is generated by this check.
"""
import hashlib
from html.parser import HTMLParser
import json
from pathlib import Path
import sys
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]


def require(condition, message):
    if not condition:
        raise ValueError(message)


def strict_json(path):
    def invalid(value):
        raise ValueError(f'non-standard JSON token {value} in {path}')
    return json.loads(Path(path).read_text(), parse_constant=invalid)


class Links(HTMLParser):
    def __init__(self):
        super().__init__()
        self.links, self.ids = [], set()
    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if 'id' in attrs:
            self.ids.add(attrs['id'])
        for attribute in ('href','src'):
            if attribute in attrs:
                self.links.append(attrs[attribute])


def check_links():
    docs = ROOT / 'docs'
    pages = list(docs.rglob('*.html'))
    require(len(pages) == 14, 'expected five main Fieldnotes pages and nine site summaries')
    parsed = {}
    for page in pages:
        parser = Links(); parser.feed(page.read_text()); parsed[page.resolve()] = parser
    checked = 0
    for page in pages:
        parser = parsed[page.resolve()]
        for link in parser.links:
            url = urlsplit(link)
            if url.scheme or url.netloc:
                continue
            target = (page.parent / unquote(url.path)).resolve() if url.path else page.resolve()
            require(target.is_relative_to(docs.resolve()), f'link escapes deployed site: {page}: {link}')
            if target.is_dir():
                target = target / 'index.html'
            require(target.exists(), f'broken local link: {page}: {link}')
            if url.fragment and target.suffix == '.html':
                require(unquote(url.fragment) in parsed[target.resolve()].ids, f'missing anchor: {page}: {link}')
            checked += 1
    return checked


def main():
    for parent in ('evidence','registry','knowledge','vendor'):
        for path in (ROOT / parent).rglob('*.json'):
            strict_json(path)
    card = strict_json(ROOT / 'evidence/run_card.json')
    first = strict_json(ROOT / 'evidence/first_pass_run_card.json')
    require(card['verdict'] == 'negative' and card['approved_for_submission'] is False, 'unexpected release approval')
    require(card['submission_slots_used'] == 0, 'a research run must not use slots')
    require(card['experiments_run'] == 1 and first['elapsed_seconds'] < 7200, 'experiment/time budget not respected')
    require(card['raster_sha256'] is None and card['submission_name'] is None, 'cannot claim a nonexistent TIFF')
    require(len(card['note']) <= 140 and len(card['planned_submission_name']) <= 140, 'name/note length')
    require(card['validator_output']['on_disk_submission_validation'] is None, 'phantom file validator')
    require(card['holdout_status'].startswith('EXPLORATORY'), 'protocol disqualification must be disclosed')
    pbsc = strict_json(ROOT / 'evidence/pbsc/run_card.json')
    require(pbsc['verdict'] == 'negative' and pbsc['ok_to_submit'] is False, 'H-PBSC must remain a negative research artifact')
    require(pbsc['holdout_dti']['label'] == 'HOLDOUT-DTI', 'H-PBSC score class')
    require(len(pbsc['submission_note']) <= 140, 'H-PBSC note length')
    tifs = list((ROOT / 'docs/downloads').glob('*.tif'))
    zips = list((ROOT / 'docs/downloads').glob('*.zip'))
    thermal = strict_json(ROOT / 'evidence/thermal/run_card.json')
    allowed_prefixes = [pbsc['submission_name'].replace('.tif', '')]
    if thermal.get('raster_name'):
        allowed_prefixes.append(thermal['raster_name'].replace('.tif', ''))
        allowed_prefixes.append('gemsass1-hvtgb-thermal-anchored-37654-20261030-zeros')  # superseded B2 duplicate log
    reg_card_path = ROOT / 'evidence/regavoid/run_card.json'
    if reg_card_path.exists():
        reg_card = strict_json(reg_card_path)
        if reg_card.get('submission_name'):
            # 2026-10-31 H-REGAVOID artifact: exact name from its (negative-verdict) run card;
            # hash-checked in the additive block below, never silently allowed.
            allowed_prefixes.append(reg_card['submission_name'].replace('.tif', ''))
    require(all(any(p.name.startswith(pref) for pref in allowed_prefixes) for p in tifs),
            'docs/downloads may only hold the named H-PBSC research TIF, the thermal-lane release, '
            'and the run-card-named H-REGAVOID artifact')
    require(all(any(p.name.startswith(pref) for pref in allowed_prefixes) for p in zips),
            'docs/downloads zip must match an allowed artifact')
    require(card['raster_sha256'] is None, 'BGAC still must not claim a TIFF')
    # --- 2026-10-30 thermal-lane release checks (additive; negatives above unchanged) ---
    if thermal:
        require(thermal['submission_slots_used'] == 0, 'the thermal run must not use slots')
        require(len(thermal['note']) <= 140 and len(thermal['submission_name']) <= 140, 'thermal name/note length')
        require(thermal['holdout_dti']['label'] == 'HOLDOUT-DTI', 'thermal score class')
        require(thermal['experiments_run'] <= thermal['experiment_budget'] == 3, 'thermal experiment budget')
        release = strict_json(ROOT / 'evidence/thermal/release.json')
        require(release['card']['raster_sha256'] == thermal['raster_sha256'], 'release/card hash drift')
        ok = release['card']['ok_to_download_and_submit']
        require(ok == all(passed for _, passed in release['gates']), 'verdict must equal the gate table')
        if ok:
            tif_path = ROOT / 'docs/downloads' / thermal['raster_name']
            require(tif_path.is_file(), 'approved release TIFF missing')
            require(hashlib.sha256(tif_path.read_bytes()).hexdigest() == thermal['raster_sha256'],
                    'approved release TIFF hash mismatch')
        require(thermal['evidence_class']['live_scores'].startswith('OWNER-REPORT'), 'live score labeling')
        canary = strict_json(ROOT / 'evidence/thermal/leakage_canary.json')
        require(canary['canary_pass'] and not canary['flagged_over_0p90'], 'thermal canary unresolved')
    # --- 2026-10-31 H-REGAVOID release checks (additive; thermal checks above unchanged) ---
    reg_path = ROOT / 'evidence/regavoid/run_card.json'
    if reg_path.exists():
        reg = strict_json(reg_path)
        require(reg['slot']['used'] == 0, 'the regavoid run must not use slots')
        require(reg['budget']['experiments_run'] <= reg['budget']['experiment_budget'] == 3,
                'regavoid experiment budget')
        require(reg['budget']['cumulative_seconds'] <= reg['budget']['seconds_budget'],
                'regavoid two-hour budget')
        require(reg['evidence_classes']['holdout_dti'] == 'HOLDOUT-DTI', 'regavoid score class')
        name = reg['submission_name'] or ''
        note = reg['submission_note'] or reg['planned_note']
        require(len(name) <= 140 and len(note) <= 140, 'regavoid name/note length')
        canary = strict_json(ROOT / 'evidence/regavoid/leakage_canary.json')
        require(not canary['flagged_over_0p90'], 'regavoid canary unresolved')
        release = strict_json(ROOT / 'evidence/regavoid/release.json')
        ok = release['card']['ok_to_download_and_submit']
        require(ok == all(passed for _, passed in release['gates']), 'regavoid verdict vs gate table')
        require(ok == reg['ok_to_submit'] and release['card']['verdict'] == reg['verdict'],
                'regavoid release/run-card verdict drift')
        if reg['raster_sha256']:
            tif_path = ROOT / 'docs/downloads' / reg['submission_name']
            require(tif_path.is_file(), 'regavoid TIFF missing')
            require(hashlib.sha256(tif_path.read_bytes()).hexdigest() == reg['raster_sha256'],
                    'regavoid TIFF hash mismatch')
        # AMEND-2 structural finding must stay on file (scoring-only diagnostic of TVGB bytes)
        diag = strict_json(ROOT / 'evidence/regavoid/tvgb_shipped_diagnostic.json')
        require(diag['holdout_dti'] == 0.0 and diag['release_claimed_value'] > 0.1,
                'TVGB shipped-bytes irregularity record changed')
        if not ok:
            require(reg['verdict'] == 'negative' and not reg['ok_to_submit'],
                    'negative regavoid release must not claim approval')
    correction = strict_json(ROOT / 'evidence/corrected_surface_novelty.json')
    require(correction['duplicate'] and not correction['cleared'], 'pre-placement stop missing')
    require(correction['candidate_values_sha256'] == card['canonical_surface_sha256'], 'corrective audit changed candidate')
    holdout = strict_json(ROOT / 'evidence/holdout.json')
    measured = holdout['scores']['BGAC-1']
    require(card['holdout_dti'] == measured['dti'] and card['ci95'] == measured['ci95'], 'score/CI transcription error')
    require(card['withheld_positive_pixels'] == measured['withheld_positive_pixels'], 'withheld count drift')
    require(all(s['withheld_positive_pixels'] == card['withheld_positive_pixels'] for s in holdout['scores'].values()), 'incomparable arm truth counts')
    require(all(not c['fails'] for c in strict_json(ROOT / 'evidence/canaries.json')['tests']), 'unresolved leakage canary')
    inventory = strict_json(ROOT / 'registry/focus_inventory.json')
    require(len(inventory['rasters']) == 414 and inventory['complete_within_scope'] and inventory['failed'] == 0, 'frozen inventory incomplete')
    history = strict_json(ROOT / 'evidence/nine_site_audit.json')
    require(len(history['rows']) == 9 and history['h33_mechanism_audit']['exact_reproduction_from_site31_base'], 'history audit incomplete')
    require(all(r['organizer_receipt'] is None and r['estimated_leaderboard_score'] is None and not r['approved_for_submission'] for r in history['rows']), 'unverified historical numbers upgraded to scores/approval')
    provenance = strict_json(ROOT / 'vendor/PROVENANCE.json')
    for name, digest in provenance['files_sha256'].items():
        require(hashlib.sha256((ROOT / 'vendor/gems57' / name).read_bytes()).hexdigest() == digest, 'shared tool modified without source fix: ' + name)
    frozen = strict_json(ROOT / 'evidence/release_checks.json')
    post = frozen.get('post_review_2026-10-30_implementation_sha256', {})
    for relative, digest in frozen['implementation_sha256'].items():
        current = hashlib.sha256((ROOT / relative).read_bytes()).hexdigest()
        # A file may change after the 2026-10-27 review only if its new bytes are pinned in the explicit post-review map.
        require(current == digest or current == post.get(relative), 'implementation changed since review: ' + relative)
    local_links = check_links()
    for path in (ROOT / 'evidence').glob('*.json'):
        require(path.read_bytes() == (ROOT / 'docs/evidence' / path.name).read_bytes(), 'site evidence stale: ' + path.name)
    for path in (ROOT / 'evidence/thermal').glob('*'):
        if path.suffix in ('.json', '.md'):
            require(path.read_bytes() == (ROOT / 'docs/evidence/thermal' / path.name).read_bytes(),
                    'site thermal evidence stale: ' + path.name)
    if (ROOT / 'evidence/regavoid').exists():
        for path in (ROOT / 'evidence/regavoid').glob('*'):
            if path.suffix in ('.json', '.md'):
                require(path.read_bytes() == (ROOT / 'docs/evidence/regavoid' / path.name).read_bytes(),
                        'site regavoid evidence stale: ' + path.name)
    print(f'PASS: frozen negative release preserved; thermal-lane release verified; H-REGAVOID release verified; 9 site summaries; {local_links} local links; strict JSON; vendor/code hashes; slots=0.')


if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError, KeyError) as error:
        print('FAIL:', error, file=sys.stderr)
        raise SystemExit(1)
